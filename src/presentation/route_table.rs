/// メソッド → パス → 行 の索引。リクエストごとに引くため、初回に1度だけ作る。
static INDEX: LazyLock<HashMap<&'static str, HashMap<&'static str, &'static RouteSpec>>> = LazyLock::new(|| {
    let mut index: HashMap<&'static str, HashMap<&'static str, &'static RouteSpec>> = HashMap::new();
    for spec in ROUTE_PERMISSIONS {
        index.entry(spec.method).or_default().insert(spec.path, spec);
    }
    index
});

/// (メソッド, パス) でルート表を引く。パスは axum の `MatchedPath`(パスの形)と同じ書式。
pub fn lookup(method: &str, path: &str) -> Option<&'static RouteSpec> {
    INDEX.get(method)?.get(path).copied()
}

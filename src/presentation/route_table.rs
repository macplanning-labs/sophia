//! presentation/route_table.rs — ルート表(DEMO-000173)。
//! employee_routes(管理者・社員共用グループ)の全ルートに、必要な権限を対応させる。
//! 許可されたものだけ通す(deny-by-default)ため、表に無いルートは、強制モードでは拒否される(ミドルウェアは後続の PR)。
//! ルートを足したら、この表にも足す(tests/route_authz_table.rs が過不足を検出する)。
//! 詳細: docs/design/詳細設計書_ロールと組織に基づく閲覧範囲.md §4

use std::collections::HashMap;
use std::sync::LazyLock;

use crate::domain::authz::Permission;

/// ルートに必要な条件。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Rule {
    /// この権限を持つ割り当てが、どこかにあること。データごとの範囲はハンドラ内で判定する。
    Perm(Permission),
    /// 本人のデータなら可。他人のデータはこの権限が必要(入口では通し、ハンドラ内で判定)。
    OwnOr(Permission),
    /// 本人のデータのみ。
    Own,
    /// ログイン済みであればよい(MFA 設定、ダッシュボード等)。
    Authenticated,
    /// 管理者(is_staff)のみ。
    AdminOnly,
}

/// ルート表の1行。handler は routes.rs の `handlers::` 以降(例: "orders::api_detail")。
#[derive(Debug, Clone, Copy)]
pub struct RouteSpec {
    pub method: &'static str,
    pub path: &'static str,
    pub handler: &'static str,
    pub rule: Rule,
}

const fn r(method: &'static str, path: &'static str, handler: &'static str, rule: Rule) -> RouteSpec {
    RouteSpec { method, path, handler, rule }
}


SET subject = '（EDI Sophia）【{{ company_name }}】重要 {{ deadline_date }}締切 {{ month_short }}分支払通知書送信の件',
    body = E'{{ partner_name }} 御中\n\nいつもお世話になっております。\n{{ company_name }}です。\n\n{{ month }} 分の支払通知書、および当社が貴社に代わり作成した請求書をご登録いたしましたので、\n下記URLより内容をご確認のうえ、ご承諾をお願いいたします。\n\n▼ 支払通知書・請求書 確認・承諾URL\n{{ token_url }}\n\n■通知書番号：{{ notice_id }}\n\n《送付物》\n「支払通知書」\n「請求書」\n　各1通\n\n《画面の見方》\n上記URLを開くと、支払通知書・請求書の内容確認画面が表示されます。\n画面上部の「支払通知書PDFを見る」「請求書PDFを見る」ボタンから、それぞれのPDFファイルをご確認・ダウンロードいただけます。\n\n《お願い》\n内容をご確認いただき、ご同意いただける場合は、同じ画面の「内容を確認し、承諾する」ボタンを押してください。\nご承諾いただけない場合は、お手数ですが本メールにご返信のうえ、内容をお知らせください。\n\nダウンロードした請求書は、御社サーバ上に必ず保管してくださいますようお願いいたします。\n\n※ このURLの有効期限は{{ expiry_days }}日間です。\n※ ご承諾いただいた場合、従来のような請求書のご返送は不要となります。\n\nご不明な点がございましたら、本メールにご返信ください。\n\n以上、よろしくお願いいたします。',
    description = '支払通知書・パートナー代理請求書送付メール（自社→パートナー。確認・承諾URL＋画面案内＋請求書PDFダウンロード案内付き。PDF添付なし）',
    updated_at = NOW()
WHERE code = 'notice_send';

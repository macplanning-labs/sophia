-- 変更点:
-- - 件名を「（EDI Sophia）【会社名】重要 締切日締切 月分支払通知書送信の件」形式に統一
--   （締切日は送信日＋{{ expiry_days }}で計算。月は年なしの短い表記）
-- - 冒頭を「{{ partner_name }} 御中」に変更（法人宛の書式）
-- - 《送付物》《画面の見方》《お願い》の見出しスタイルを追加
--   （画面の見方は、確認ページ /token/{uuid} の実際のボタン配置に合わせて具体的に案内。
--     JWCの担当者から操作方法について電話で問い合わせがあったため、2026-07-30に追加）
-- - 請求書PDFのダウンロード・保管依頼を追加
-- - 「締切：YYYY年M月D日」のような固定日付ではなく、
--   024_fix_order_send_expiry_text.sql と同様に {{ expiry_days }}（動的値）を使用


-- order_send テンプレート文面の刷新（037と同じ方針。イー・ビジネスEDI-OASISの文面を参考にアレンジ）
-- ============================================================
-- 変更点:
-- - 件名を「（EDI Sophia）【会社名】重要 締切日締切 月分注文書送信の件」形式に統一
-- - 冒頭を「{{ partner_name }} 御中」に変更（法人宛の書式）
-- - 《送付物》《画面の見方》《お願い》の見出しスタイルを追加
--   （画面の見方は /token/{uuid} の実際のボタン配置に合わせて案内。
--     注文請書は承諾後にのみ表示される点を反映）

UPDATE s_email_template
SET subject = '（EDI Sophia）【{{ company_name }}】重要 {{ deadline_date }}締切 {{ month_short }}分注文書送信の件',
    body = E'{{ partner_name }} 御中\n\nいつもお世話になっております。\n{{ company_name }}です。\n\n{{ month }} 分の注文書をご登録いたしましたので、\n下記URLより内容をご確認のうえ、ご承諾をお願いいたします。\n\n▼ 注文書 確認・承諾URL\n{{ token_url }}\n\n■注文書番号：{{ order_id }}\n\n《送付物》\n「注文書」\n　1通\n\n《画面の見方》\n上記URLを開くと、注文書の内容確認画面が表示されます。\n画面上部の「注文書PDFを見る」ボタンからPDFファイルをご確認・ダウンロードいただけます。\nご承諾後は、同じ画面に「注文請書PDFを見る」ボタンが表示され、注文請書PDFもダウンロードいただけるようになります。\n\n《お願い》\n内容をご確認いただき、ご同意いただける場合は、画面の「内容を確認し、承諾する」ボタンを押してください。\nご承諾いただけない場合は、お手数ですが本メールにご返信のうえ、内容をお知らせください。\n\nダウンロードしたファイルは、御社サーバ上に必ず保管してくださいますようお願いいたします。\n\n※ このURLの有効期限は{{ expiry_days }}日間です。\n※ ご承諾いただいた場合、従来のような注文請書のご返送は不要となります。\n\nご不明な点がございましたら、本メールにご返信ください。\n\n以上、よろしくお願いいたします。',
    description = '注文書送付メール（自社→パートナー。確認・承諾URL＋画面案内付き）',
    updated_at = NOW()
WHERE code = 'order_send';
